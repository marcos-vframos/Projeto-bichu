export const BACKUP_TABLES=['pilot_accounts','pilot_records','pilot_files','pilot_events','pilot_changes','pilot_devices','pilot_sessions','pilot_login_attempts']
export async function backupPage(db,url){
 const table=url.searchParams.get('table'),offset=Number(url.searchParams.get('offset')||0)
 if(!BACKUP_TABLES.includes(table)||!Number.isSafeInteger(offset)||offset<0)throw Error('Página inválida')
 const rows=(await db.prepare(`SELECT * FROM ${table} ORDER BY ${table==='pilot_sessions'?'token_hash':table==='pilot_login_attempts'?'email':'id'} LIMIT 201 OFFSET ?`).bind(offset).all()).results
 return {format:'meu-bichu-backup-v1',table,items:rows.slice(0,200),nextOffset:rows.length>200?offset+200:null}
}
// Intended for an empty recovery database only, never merge into existing production data.
export async function restoreDatabase(db,tables){
 for(const table of BACKUP_TABLES)if((await db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).first()).n)throw Error('Restauração exige banco vazio')
 if(BACKUP_TABLES.some(t=>!Array.isArray(tables[t])))throw Error('Backup incompleto')
 for(const table of BACKUP_TABLES){
  if(table==='pilot_changes')await db.prepare('DELETE FROM pilot_changes').run() // replace audit generated by record triggers
  for(const row of tables[table]){const keys=Object.keys(row);if(!keys.length||keys.some(k=>!/^\w+$/.test(k)))throw Error('Coluna inválida');await db.prepare(`INSERT INTO ${table} (${keys.join(',')}) VALUES (${keys.map(()=>'?').join(',')})`).bind(...keys.map(k=>row[k])).run()}
 }
}
